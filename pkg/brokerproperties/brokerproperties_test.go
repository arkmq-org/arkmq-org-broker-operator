var _ = Describe("BrokerPropertiesData", func() {
	It("returns a map containing the broker.properties key for regular props", func() {
		data := BrokerPropertiesData([]string{"foo=bar", "baz=qux"})
		Expect(data).To(HaveKey(BrokerPropertiesName))
	})

	It("places regular properties into broker.properties content", func() {
		data := BrokerPropertiesData([]string{"foo=bar"})
		content := string(data[BrokerPropertiesName])
		Expect(content).To(ContainSubstring("foo=bar"))
	})

	It("routes an ordinal-prefixed property into its own per-ordinal file", func() {
		data := BrokerPropertiesData([]string{"broker-0.foo=bar"})
		Expect(data).To(HaveKey("broker-0" + OrdinalPrefixSep + BrokerPropertiesName))
		Expect(data).NotTo(HaveKey("broker-1" + OrdinalPrefixSep + BrokerPropertiesName))
	})

	It("the per-ordinal file contains only the value portion, not the ordinal prefix", func() {
		data := BrokerPropertiesData([]string{"broker-0.foo=bar"})
		content := string(data["broker-0"+OrdinalPrefixSep+BrokerPropertiesName])
		Expect(content).To(ContainSubstring("foo=bar"))
		Expect(content).NotTo(ContainSubstring("broker-0"))
	})

	It("accumulates multiple properties for the same ordinal in one file", func() {
		data := BrokerPropertiesData([]string{"broker-0.foo=bar", "broker-0.baz=qux"})
		content := string(data["broker-0"+OrdinalPrefixSep+BrokerPropertiesName])
		Expect(content).To(ContainSubstring("foo=bar"))
		Expect(content).To(ContainSubstring("baz=qux"))
	})

	It("creates separate files for distinct ordinals", func() {
		data := BrokerPropertiesData([]string{"broker-0.foo=bar", "broker-1.baz=qux"})
		Expect(data).To(HaveKey("broker-0" + OrdinalPrefixSep + BrokerPropertiesName))
		Expect(data).To(HaveKey("broker-1" + OrdinalPrefixSep + BrokerPropertiesName))
	})

	It("keeps regular props out of per-ordinal files and vice versa", func() {
		data := BrokerPropertiesData([]string{"shared=yes", "broker-0.ordinal=only"})
		sharedContent := string(data[BrokerPropertiesName])
		ordinalContent := string(data["broker-0"+OrdinalPrefixSep+BrokerPropertiesName])
		Expect(sharedContent).To(ContainSubstring("shared=yes"))
		Expect(sharedContent).NotTo(ContainSubstring("ordinal=only"))
		Expect(ordinalContent).To(ContainSubstring("ordinal=only"))
		Expect(ordinalContent).NotTo(ContainSubstring("shared=yes"))
	})

	It("returns only broker.properties when the list is empty", func() {
		data := BrokerPropertiesData([]string{})
		Expect(data).To(HaveLen(1))
		Expect(data).To(HaveKey(BrokerPropertiesName))
	})
})

