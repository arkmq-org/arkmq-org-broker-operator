var _ = Describe("ReadReplaceEscapes", func() {
	It("replaces escaped spaces", func() {
		result := ReadReplaceEscapes([]string{`key=val\ ue`})
		Expect(result[0]).To(ContainSubstring("val ue"))
	})

	It("replaces escaped colons", func() {
		result := ReadReplaceEscapes([]string{`key=val\:ue`})
		Expect(result[0]).To(ContainSubstring("val:ue"))
	})

	It("replaces escaped equals signs", func() {
		result := ReadReplaceEscapes([]string{`key=val\=ue`})
		Expect(result[0]).To(ContainSubstring("val=ue"))
	})

	It("replaces escaped double quotes", func() {
		result := ReadReplaceEscapes([]string{`key=val\"ue`})
		Expect(result[0]).To(ContainSubstring(`val"ue`))
	})

	It("trims whitespace between key and = separator", func() {
		result := ReadReplaceEscapes([]string{"key  =  value"})
		Expect(result[0]).To(Equal("key=value"))
	})

	It("returns the input unchanged when there are no escapes", func() {
		result := ReadReplaceEscapes([]string{"foo=bar"})
		Expect(result[0]).To(Equal("foo=bar"))
	})

	It("passes through entries that have no = separator", func() {
		result := ReadReplaceEscapes([]string{"no-separator"})
		Expect(result[0]).To(Equal("no-separator"))
	})
})

